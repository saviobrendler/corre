// Gramática: "no Japão", "na França", "em Portugal", "nos Estados Unidos".
const ART_PREP = {
  em: { o: "no", a: "na", os: "nos", as: "nas", "": "em" },
  de: { o: "do", a: "da", os: "dos", as: "das", "": "de" },
  para: { o: "para o", a: "para a", os: "para os", as: "para as", "": "para" }
};

// Monta o registro completo de cada país a partir da lista. mult = salário relativo ao Brasil.
function montarMundo() {
  const BRL_USD = 5.4,
    paises = {};
  for (const [c, n, art, reg, idioma, moeda, porUSD, ppp, nomes, cids] of MUNDO_LISTA) {
    const mult = c === "BR" ? 1 : Math.max(.45, Math.min(3, Math.round(10 * Math.pow(ppp / 21, .6)) / 10));
    paises[c] = {
      n, art, reg, idioma, nomes,
      moeda: { s: moeda, taxa: porUSD / BRL_USD },
      cid: cids ? cids.split(";").map(x => `${x} (${n})`) : null,
      mult,
      alu: Math.max(900, 100 * Math.round(24 * mult)),
      custo: Math.max(6e3, 1e3 * Math.round(16 * mult)),
      visto: Math.max(30, Math.min(95, Math.round(100 - 22 * mult)))
    };
  }
  return paises;
}
const MUNDO = montarMundo();

// O ⁠ (invisível) marca o nome como intencional, pra localizar() não trocar "Brasil" pelo país atual.
function nomePais(c) { return "⁠" + (MUNDO[c] || MUNDO.BR).n }
function emPais(c) { const p = MUNDO[c] || MUNDO.BR; return `${ART_PREP.em[p.art]} ${nomePais(c)}` }
function dePais(c) { const p = MUNDO[c] || MUNDO.BR; return `${ART_PREP.de[p.art]} ${nomePais(c)}` }
function paraPais(c) { const p = MUNDO[c] || MUNDO.BR; return `${ART_PREP.para[p.art]} ${nomePais(c)}` }

// Formata um valor em reais na moeda de um país, no padrão brasileiro de milhar.
// redondo: arredonda pra 2 algarismos significativos (valores escritos nos textos, tipo "R$ 50" → "¥ 1.400").
function moedaFmt(reais, c, redondo) {
  const m = (MUNDO[c] || MUNDO.BR).moeda;
  let v = reais * m.taxa;
  if (redondo && Math.abs(v) >= 100) { const p = Math.pow(10, Math.floor(Math.log10(Math.abs(v))) - 1); v = Math.round(v / p) * p }
  const a = Math.abs(v),
    num = a > 0 && a < 10 && m.taxa < .5 ? a.toFixed(2).replace(".", ",") : Math.round(a).toString().replace(/\B(?=(\d{3})+(?!\d))/g, ".");
  return (v < 0 ? "-" : "") + m.s + " " + num;
}

function moedaCurta(reais, c, redondo) {
  const m = (MUNDO[c] || MUNDO.BR).moeda,
    v = reais * m.taxa,
    a = Math.abs(v),
    s = v < 0 ? "-" : "";
  if (a >= 1e9) return s + m.s + " " + (a / 1e9).toFixed(a >= 1e10 ? 0 : 1).replace(".", ",") + " bi";
  if (a >= 1e6) return s + m.s + " " + (a / 1e6).toFixed(a >= 1e7 ? 0 : 1).replace(".", ",") + " mi";
  if (a >= 1e4) return s + m.s + " " + Math.round(a / 1e3) + " mil";
  return moedaFmt(reais, c, redondo);
}

